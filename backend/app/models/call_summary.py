"""
CallSummary database model for post-call insights, BANT extraction, and action items.
"""

from typing import Any, Dict, List
import uuid
from sqlalchemy import String, Boolean, Text, ForeignKey
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin


class CallSummary(Base, TimestampMixin):
    """
    Structured post-call summary generated by LLM analysis pipeline.
    Stores extracted BANT attributes, objections, action items, and sentiment.
    """
    __tablename__ = "call_summaries"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )
    call_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("calls.id", ondelete="CASCADE"),
        unique=True,
        index=True,
        nullable=False,
    )
    summary_text: Mapped[str] = mapped_column(Text, nullable=False)
    key_points: Mapped[List[str]] = mapped_column(JSONB, default=list, nullable=False)
    bant_analysis: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    action_items: Mapped[List[str]] = mapped_column(JSONB, default=list, nullable=False)
    overall_sentiment: Mapped[str] = mapped_column(String(32), default="neutral", nullable=False)
    follow_up_needed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # Relationships
    call: Mapped["Call"] = relationship("Call", back_populates="summary")

    def __repr__(self) -> str:
        return f"<CallSummary(call_id={self.call_id}, sentiment={self.overall_sentiment}, follow_up={self.follow_up_needed})>"
